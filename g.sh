from pathlib import Path
import re
import sys

ROOT = Path.cwd()
REPORT = next(ROOT.glob("REMEDIATION_REPORT_*.md"))

def read(rel):
    path = ROOT / rel
    if not path.is_file():
        raise RuntimeError(f"Required file missing: {rel}")
    return path.read_text()

def write(rel, content):
    (ROOT / rel).write_text(content)

def replace_once(source, old, new, label):
    count = source.count(old)
    if count != 1:
        raise RuntimeError(
            f"{label}: expected exactly one matching source block; found {count}. "
            "No change made to this file."
        )
    return source.replace(old, new, 1)

def record(message):
    with REPORT.open("a") as f:
        f.write(f"\n- {message}\n")
    print("[PATCH]", message)

def uncertainty_patch():
    rel = "src/ecofac/decision/uncertainty.py"
    source = read(rel)

    old = """    if estimated_count == 0 and unknown_count == 0:
        return ModelUncertaintyLevel.LOW, rationale
    if estimated_count <= measured_count and has_any_tolerance:
        return ModelUncertaintyLevel.MODERATE, rationale
    return ModelUncertaintyLevel.HIGH, rationale
"""

    new = """    # Measurement provenance is not the same thing as measurement accuracy.
    # A MEASURED value without a tolerance is not evidence of low uncertainty.
    if not has_any_tolerance:
        rationale.append(
            "measurement uncertainty is UNKNOWN because no tolerance metadata "
            "was supplied"
        )
        return ModelUncertaintyLevel.UNKNOWN, rationale

    if estimated_count == 0 and unknown_count == 0:
        return ModelUncertaintyLevel.MODERATE, rationale
    if estimated_count <= measured_count:
        return ModelUncertaintyLevel.MODERATE, rationale
    return ModelUncertaintyLevel.HIGH, rationale
"""

    source = replace_once(
        source, old, new, "Uncertainty classification"
    )
    write(rel, source)
    record("Changed missing-tolerance classification: measured does not automatically mean LOW uncertainty.")

def transparent_patch():
    rel = "src/ecofac/decision/transparent.py"
    source = read(rel)

    if "import math\n" not in source:
        source = source.replace(
            "from typing import Any\n",
            "import math\nfrom typing import Any\n",
            1,
        )

    old = """    predicted_it = current_it + effective_it_delta
    predicted_cooling = current_cooling + effective_cooling_delta
"""

    new = """    predicted_it = current_it + effective_it_delta
    predicted_cooling = current_cooling + effective_cooling_delta

    # Reject invalid physical states. Never turn a negative prediction into
    # zero: doing so could hide an impossible proposal and create a false pass.
    numeric_values = (
        current_it,
        current_cooling,
        effective_it_delta,
        effective_cooling_delta,
        predicted_it,
        predicted_cooling,
    )
    if not all(math.isfinite(value) for value in numeric_values):
        raise ValueError("Decision loads and proposed changes must be finite numbers.")

    if current_it < 0 or current_cooling < 0:
        raise ValueError("Current operational loads cannot be negative.")

    if predicted_it < 0:
        raise ValueError(
            "Proposed change would drive IT load below zero "
            f"({predicted_it} kW)."
        )

    if predicted_cooling < 0:
        raise ValueError(
            "Proposed change would drive cooling load below zero "
            f"({predicted_cooling} kW)."
        )
"""

    source = replace_once(
        source, old, new, "Predicted-load validation"
    )

    # Remove silent clamping from the canonical context constructor.
    old_context = """            current_electrical_kw=max(0.0, current_electrical),
            current_cooling_kw=max(0.0, current_cooling),
            predicted_electrical_kw=max(0.0, predicted_electrical),
            predicted_cooling_kw=max(0.0, predicted_cooling),
"""
    new_context = """            current_electrical_kw=current_electrical,
            current_cooling_kw=current_cooling,
            predicted_electrical_kw=predicted_electrical,
            predicted_cooling_kw=predicted_cooling,
"""

    source = replace_once(
        source, old_context, new_context, "Decision context clamping"
    )

    # Remove clamping from sensitivity calculations too.
    source = source.replace(
        "predicted_electrical=max(0.0, predicted_it + delta),",
        "predicted_electrical=predicted_it + delta,",
    )
    source = source.replace(
        "current_electrical=max(0.0, measured_value),",
        "current_electrical=measured_value,",
    )
    source = source.replace(
        "predicted_cooling=max(0.0, predicted_cooling + delta),",
        "predicted_cooling=predicted_cooling + delta,",
    )
    source = source.replace(
        "current_cooling=max(0.0, measured_value),",
        "current_cooling=measured_value,",
    )

    write(rel, source)
    record("Added finite/non-negative load validation and removed silent zero clamping from transparent decisions and sensitivity calculations.")

def store_patch():
    rel = "src/ecofac/decision/store.py"
    source = read(rel)

    start = source.find("def walk_supersession_chain(")
    if start < 0:
        raise RuntimeError("Could not locate walk_supersession_chain().")

    # This function is at the end of the currently inspected source file.
    old_function = source[start:]

    if "def walk_supersession_chain(" not in old_function:
        raise RuntimeError("Supersession function boundary not found.")

    new_function = '''def walk_supersession_chain(
    conn: sqlite3.Connection, decision_id: str
) -> list[sqlite3.Row]:
    """Return the complete branching supersession history containing an ID.

    The result starts at the root ancestor and includes every descendant,
    rather than silently following only the first child.
    """
    exists = conn.execute(
        "SELECT 1 FROM decisions WHERE id = ?", (decision_id,)
    ).fetchone()
    if exists is None:
        return []

    # Find the root ancestor.
    root = decision_id
    visited_ancestors = {root}
    while True:
        row = conn.execute(
            "SELECT supersedes FROM decisions WHERE id = ?", (root,)
        ).fetchone()
        if row is None or not row["supersedes"]:
            break
        parent = row["supersedes"]
        if parent in visited_ancestors:
            break
        visited_ancestors.add(parent)
        root = parent

    # Walk all branches deterministically.
    ordered_ids: list[str] = []
    pending = [root]
    visited: set[str] = set()

    while pending:
        current = pending.pop(0)
        if current in visited:
            continue
        visited.add(current)
        ordered_ids.append(current)

        children = conn.execute(
            "SELECT id FROM decisions WHERE supersedes = ? "
            "ORDER BY created_at, id",
            (current,),
        ).fetchall()
        pending.extend(row["id"] for row in children)

    if decision_id not in visited:
        return []

    placeholders = ",".join("?" for _ in ordered_ids)
    rows = conn.execute(
        f"SELECT * FROM decisions WHERE id IN ({placeholders}) "
        "ORDER BY created_at, id",
        ordered_ids,
    ).fetchall()
    return list(rows)
'''

    write(rel, source[:start] + new_function)
    record("Changed supersession traversal to include all descendant branches.")

def add_regression_tests():
    test_dir = ROOT / "tests" / "regression"
    test_dir.mkdir(parents=True, exist_ok=True)
    test_file = test_dir / "test_local_remediation_guards.py"

    test_file.write_text('''"""Regression tests for local EcoFac safety corrections."""

import math
import pytest

from ecofac.decision.measurements import (
    MeasurementSource,
    RichMeasurement,
)
from ecofac.decision.uncertainty import (
    ModelUncertaintyLevel,
    _assess_model_uncertainty,
)


def measured(name="IT load", value=400.0):
    return RichMeasurement(
        name=name,
        value=value,
        unit="kW",
        source=MeasurementSource.MEASURED,
    )


def test_measured_without_tolerance_is_not_low_uncertainty():
    level, rationale = _assess_model_uncertainty([measured()])
    assert level == ModelUncertaintyLevel.UNKNOWN
    assert any("UNKNOWN" in item for item in rationale)


def test_measured_with_explicit_tolerance_is_not_claimed_perfect():
    measurement = RichMeasurement(
        name="IT load",
        value=400.0,
        unit="kW",
        source=MeasurementSource.MEASURED,
        uncertainty={"absolute_tolerance": 2.0},
    )
    level, _ = _assess_model_uncertainty([measurement])
    assert level == ModelUncertaintyLevel.MODERATE


def test_measurement_model_accepts_finite_demo_value():
    assert math.isfinite(measured().value)
''')

    record("Added regression tests for uncertainty classification.")

def main():
    uncertainty_patch()
    transparent_patch()
    store_patch()
    add_regression_tests()

