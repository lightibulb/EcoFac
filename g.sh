python -c 'import sys; assert sys.version_info >= (3, 11)' \
  || die "EcoFac requires Python 3.11 or newer."

log "Creating a local backup"

mkdir -p "$BACKUP"

tar \
  --exclude='.git' \
  --exclude='.venv' \
  --exclude='venv' \
  --exclude='__pycache__' \
  --exclude='.pytest_cache' \
  --exclude='.ruff_cache' \
  --exclude='*.db' \
  --exclude='*.sqlite' \
  --exclude='*.sqlite3' \
  -czf "$BACKUP/ecofac_source.tar.gz" \
  -C "$ROOT" .

